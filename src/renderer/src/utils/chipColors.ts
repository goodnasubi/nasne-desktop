const TEXT_COLOR = 'hsl(0, 0%, 100%)'
const DEFAULT_BG = 'hsl(220, 40%, 48%)'

export function getGenreChipStyle(genreName: string): { backgroundColor: string; color: string } {
  // 1. 主ジャンル完全一致
  if (GENRE_COLOR_MAP[genreName]) {
    return { backgroundColor: GENRE_COLOR_MAP[genreName], color: TEXT_COLOR }
  }
  // 2. 副ジャンル直接マッピング
  const parent = GENRE_DETAIL_PARENT[genreName]
  if (parent && GENRE_COLOR_MAP[parent]) {
    return { backgroundColor: GENRE_COLOR_MAP[parent], color: TEXT_COLOR }
  }
  // 3. 部分一致フォールバック（主ジャンル名が副ジャンル名に含まれる場合）
  for (const key of Object.keys(GENRE_COLOR_MAP)) {
    if (genreName.includes(key) || key.includes(genreName)) {
      return { backgroundColor: GENRE_COLOR_MAP[key], color: TEXT_COLOR }
    }
  }
  return { backgroundColor: DEFAULT_BG, color: TEXT_COLOR }
}

