export function getChannelChipStyle(channelName: string): { backgroundColor: string; color: string } {
  const TEXT = 'hsl(0, 0%, 90%)'
  for (const [key, color] of Object.entries(CHANNEL_COLOR_MAP)) {
    if (channelName.includes(key)) {
      return { backgroundColor: color, color: TEXT }
    }
  }
  let hash = 0
  for (let i = 0; i < channelName.length; i++) {
    hash += channelName.charCodeAt(i)
  }
  const hue = hash % 360
  return {
    backgroundColor: `hsl(${hue}, 50%, 28%)`,
    color: TEXT,
  }
}
